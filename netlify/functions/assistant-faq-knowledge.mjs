export function getRelevantFaqContext(query = "", maxEntries = 6, useDefault = true) {
  const selected = selectRelevantFaqs(query, maxEntries, useDefault);

  if (!selected.length) {
    return "";
  }

  return [
    "FAQ aprobado por UroPanama. Responde en español latinoamericano salvo que el paciente escriba en inglés. No diagnostiques, no prometas disponibilidad y usa estas respuestas como fuente:",
    ...selected.map(
      (faq) => `Pregunta: ${faq.question}\nRespuesta aprobada: ${faq.answer}`,
    ),
  ].join("\n");
}

export function selectRelevantFaqs(query = "", maxEntries = 6, useDefault = true) {
  const terms = tokenize(query);

  if (!terms.length) {
    return useDefault
      ? assistantFaqs.filter((faq) => defaultQuestions.has(faq.question))
      : [];
  }

  const scored = assistantFaqs
    .map((faq) => ({ faq, score: scoreFaq(faq, terms) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score);

  if (!scored.length) {
    return useDefault
      ? assistantFaqs.filter((faq) => defaultQuestions.has(faq.question))
      : [];
  }

  return scored.slice(0, maxEntries).map((item) => item.faq);
}

function scoreFaq(faq, terms) {
  const question = normalize(faq.question);
  const answer = normalize(faq.answer);
  let score = 0;

  for (const term of terms) {
    if (question.includes(term)) score += 3;
    if (answer.includes(term)) score += 1;
  }

  return score;
}

function tokenize(value) {
  return normalize(value)
    .split(/[^a-z0-9]+/)
    .filter((term) => term.length >= 4 && !stopWords.has(term));
}

function normalize(value) {
  return String(value)
    .toLocaleLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}

